using NOpenNLP.Tools.Stemmer.Snowball;
using NOpenNLP.Tools.Support;
using NUnit.Framework;
using NUnit.Framework.Legacy;

namespace NOpenNLP.Tools.Stemmer;

/// <summary>
/// Pins the five languages where the generated stemmers deliberately differ from
/// Apache OpenNLP 1.9.4.
/// </summary>
/// <remarks>
/// The stemmers are generated by the Snowball compiler pinned to 2.0.0. Measured
/// over the full Snowball vocabularies, 16 of the 21 languages are byte-identical
/// to OpenNLP 1.9.4. Five are not, because OpenNLP ships
/// generated code that predates several upstream fixes, and the sources behind it
/// survive at no revision that can be pinned: its Finnish and Hungarian stemmers
/// were committed 2013-11-20, before the Snowball project moved to git.
/// <para/>
/// For four of them the difference is the fix, so these are kept rather than
/// reverted. Arabic is the exception: neither side is clearly better, and it is kept
/// because no Snowball revision reproduces OpenNLP's generated code.
/// The cases below are the concrete evidence for that claim, and exist so the
/// deviation cannot drift silently: if a regeneration changes one of these, the
/// pin or the algorithm moved, and that needs a deliberate decision rather than a
/// surprise.
/// <para/>
/// The corresponding upstream assertions all still pass - see
/// <c>SnowballStemmerTest</c>. None of them touch an affected word.
/// </remarks>
[NOpenNLPSpecific]
public class SnowballDeviationTest
{
    /// <summary>
    /// OpenNLP 1.9.4 stems these four inflections of the Finnish noun <c>aarre</c>
    /// ("treasure") to four different stems - aartees, aarteid, aarteis, aart -
    /// so a search for one form cannot match a document containing another.
    /// </summary>
    [Test]
    public void TestFinnishConflatesCaseFormsOfOneNoun()
    {
        SnowballStemmer stemmer = new SnowballStemmer(ALGORITHM.FINNISH);

        ClassicAssert.AreEqual("aart", stemmer.Stem("aarteeseen"));
        ClassicAssert.AreEqual("aart", stemmer.Stem("aarteiden"));
        ClassicAssert.AreEqual("aart", stemmer.Stem("aarteisiin"));
        ClassicAssert.AreEqual("aart", stemmer.Stem("aarteet"));
    }

    /// <summary>
    /// OpenNLP 1.9.4 leaves the Hungarian ablative and delative case suffixes
    /// (-ról/-ről, -tól/-től) entirely unstripped, stemming each of these words
    /// to itself.
    /// </summary>
    [Test]
    public void TestHungarianStripsAblativeAndDelativeSuffixes()
    {
        SnowballStemmer stemmer = new SnowballStemmer(ALGORITHM.HUNGARIAN);

        ClassicAssert.AreEqual("adatvédel", stemmer.Stem("adatvédelemről"));
        ClassicAssert.AreEqual("ak", stemmer.Stem("akikről"));
        ClassicAssert.AreEqual("adófizető", stemmer.Stem("adófizetőktől"));
    }

    /// <summary>
    /// Snowball commit 86ceab9, "Recognize suffixes that begin with diaereses",
    /// which OpenNLP 1.9.4 predates. <c>aigu</c> and <c>aiguë</c> are the
    /// masculine and feminine of one adjective; upstream stems the latter to
    /// itself.
    /// </summary>
    [Test]
    public void TestFrenchRecognizesSuffixesBeginningWithDiaereses()
    {
        SnowballStemmer stemmer = new SnowballStemmer(ALGORITHM.FRENCH);

        ClassicAssert.AreEqual("aigu", stemmer.Stem("aiguë"));
        ClassicAssert.AreEqual("aigu", stemmer.Stem("aiguës"));
        ClassicAssert.AreEqual("archa", stemmer.Stem("archaïque"));
        ClassicAssert.AreEqual("archa", stemmer.Stem("archaïsme"));
    }

    /// <summary>
    /// The Indonesian deviation runs the other way: the port stems less. In these
    /// loanwords the final <c>-i</c> belongs to the root, and OpenNLP 1.9.4 strips
    /// it anyway (demokrasi -> demokras), corrupting the stem.
    /// </summary>
    [Test]
    public void TestIndonesianKeepsRootFinalIOfLoanwords()
    {
        SnowballStemmer stemmer = new SnowballStemmer(ALGORITHM.INDONESIAN);

        ClassicAssert.AreEqual("demokrasi", stemmer.Stem("demokrasi"));
        ClassicAssert.AreEqual("organisasi", stemmer.Stem("organisasi"));
        ClassicAssert.AreEqual("abdikasi", stemmer.Stem("abdikasi"));
    }

    /// <summary>
    /// The counterpart to <see cref="TestIndonesianKeepsRootFinalIOfLoanwords"/>:
    /// a genuine <c>-i</c> suffix is still stripped, so the fix recovered
    /// precision without giving up suffix handling. Both implementations agree
    /// on these.
    /// </summary>
    [Test]
    public void TestIndonesianStillStripsGenuineSuffixes()
    {
        SnowballStemmer stemmer = new SnowballStemmer(ALGORITHM.INDONESIAN);

        ClassicAssert.AreEqual("ambil", stemmer.Stem("mengambili"));
        ClassicAssert.AreEqual("emu", stemmer.Stem("menemui"));
    }

    /// <summary>
    /// OpenNLP 1.9.4 and 1.9.5 strip a leading conjunction or preposition (wa-, fa-,
    /// li-) that the Snowball 2.0.0 Arabic algorithm keeps: upstream stems each of
    /// these to <c>كتاب</c>. 2,326,850 of the 2,326,917 differing words, out of
    /// 9,196,215, are of this shape.
    /// </summary>
    [Test]
    public void TestArabicKeepsLeadingConjunctionsAndPrepositions()
    {
        SnowballStemmer stemmer = new SnowballStemmer(ALGORITHM.ARABIC);

        ClassicAssert.AreEqual("والكتاب", stemmer.Stem("والكتاب"));
        ClassicAssert.AreEqual("فالكتاب", stemmer.Stem("فالكتاب"));
        ClassicAssert.AreEqual("لكتاب", stemmer.Stem("لكتاب"));
    }

    /// <summary>
    /// The other side of the Arabic deviation: upstream over-strips, taking the
    /// root's kaf out of <c>أأكابد</c> (upstream <c>اابد</c>), where the port keeps it.
    /// </summary>
    [Test]
    public void TestArabicKeepsTheRootOfHamzaPrefixedWords()
    {
        SnowballStemmer stemmer = new SnowballStemmer(ALGORITHM.ARABIC);

        ClassicAssert.AreEqual("اكابد", stemmer.Stem("أأكابد"));
    }
}
